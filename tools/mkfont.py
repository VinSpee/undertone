#!/usr/bin/env python3
"""Generates the firmware's bitmap fonts: ANTI-ALIASED (4-bit alpha), proportional.

   python3 tools/mkfont.py [otf_folder]         firmware/fonts.h from Inter (SIL OFL 1.1): the base firmware's fonts,
                                                which PALETTE and STARTER draw with
   python3 tools/mkfont.py gamut [ttf_folder]   firmware/apps/gamut/ui_fonts.h from B612 and B612 Mono (SIL OFL 1.1):
                                                Gamut's own (the four .ttf files of ofl/b612 and ofl/b612mono in
                                                https://github.com/google/fonts)

Each font: a common cell height H, and per character an advance (width) + an advance x H bitmap at
4 bits per pixel (2 pixels per byte). The firmware blends text / background colour by alpha (16 levels).
The files in the repository were made with Pillow 10.4: another version may set a pixel differently.
"""
import sys, os, string
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
ASCII = "".join(chr(c) for c in range(0x20, 0x7F))
FIGURES = " 0123456789+-.%/:=#'()!" + string.ascii_lowercase + string.ascii_uppercase   # figures, their units, a few words
SETS = {
    "base": {
        "out": "firmware/fonts.h", "src": "/usr/share/fonts/opentype/inter", "face": "Inter",
        "head": ["/* GENERATED by tools/mkfont.py — do not edit. Inter font (Rasmus Andersson), SIL Open Font License 1.1,",
                 " * see firmware/fonts/LICENSE-Inter.txt. Anti-aliased bitmaps, 4 bits/pixel (2 pixels per byte, high nibble on the left). */",
                 "#pragma once", "#include <stdint.h>",
                 "typedef struct { uint8_t h; const char *chars; uint8_t n; const uint8_t *adv; const uint32_t *off; const uint8_t *bits; } op_font;",
                 ""],
        "fonts": [   # C name, file, size px, character set, extra tracking
            ("FT_SM", "Inter-SemiBold.otf", 12, ASCII, 0),
            ("FT_MD", "Inter-Bold.otf", 19, ASCII, 0),
            ("FT_LG", "Inter-Bold.otf", 72, " #-ABCDEFG", 0),
            ("FT_NM", "Inter-ExtraBold.otf", 26, ASCII, 0),        # v36: the preset name on the play screen
            ("FT_XL", "Inter-ExtraBold.otf", 58, "0123456789", 0),  # v36: the preset number
        ],
    },
    # Gamut's screen: B612 for text, B612 Mono for figures. The sizes follow the capitals' height the design asks for
    # (in px, after each entry): the preset number and the tuner note are the two texts read from five feet.
    "gamut": {
        "out": "firmware/apps/gamut/ui_fonts.h", "src": ".", "face": "B612",
        "head": ["/* GENERATED by tools/mkfont.py gamut — do not edit. Gamut's own fonts (the base firmware's are firmware/fonts.h):",
                 " * B612 and B612 Mono (The B612 Project Authors), SIL Open Font License 1.1, see firmware/fonts/LICENSE-B612.txt.",
                 " * These bitmaps are a modified version of the fonts. Anti-aliased, 4 bits/pixel (2 pixels per byte, high nibble on",
                 " * the left); op_font is firmware/fonts.h's. */",
                 "#pragma once",
                 ""],
        "fonts": [
            ("GF_LB", "B612-Regular.ttf", 13, ASCII, 0),              # labels, hints, messages: 10
            ("GF_TX", "B612-Regular.ttf", 19, ASCII, 0),              # models, titles, names in a list: 14
            ("GF_NM", "B612-Bold.ttf", 28, ASCII, 0),                 # the preset name: 22, the most 13 characters allow
            ("GF_HE", "B612-Bold.ttf", 52, " abcdefgilmnopqrstvxy", 0),  # the selected block's label (the 12 labels' letters): 40
            ("GF_LG", "B612-Bold.ttf", 106, " #-ABCDEFG", 0),         # the tuner note: 81
            ("GF_MS", "B612Mono-Regular.ttf", 12, FIGURES, 0),        # small figures: 9
            ("GF_MD", "B612Mono-Regular.ttf", 19, FIGURES, 0),        # values: 14
            ("GF_XL", "B612Mono-Bold.ttf", 75, "0123456789", 0),      # the preset number: 58
        ],
    },
}
args = sys.argv[1:]
SET = SETS[args.pop(0)] if args and args[0] in SETS else SETS["base"]
SRC = args[0] if args else SET["src"]
OUT = os.path.join(ROOT, SET["out"])

def build(name, fname, size, chars, track):
    f = ImageFont.truetype(os.path.join(SRC, fname), size)
    asc, desc = f.getmetrics()
    # common vertical box: from the highest to the lowest row over the whole character set
    top, bot = 10**9, -10**9
    for ch in chars:
        bb = f.getbbox(ch)
        if bb[2] > bb[0]:
            top, bot = min(top, bb[1]), max(bot, bb[3])
    if top > bot: top, bot = 0, asc + desc
    H = bot - top
    glyphs = []
    for ch in chars:
        adv = int(round(f.getlength(ch))) + track
        if adv < 1: adv = 1
        im = Image.new("L", (adv + 4, H), 0)
        ImageDraw.Draw(im).text((0, -top), ch, font=f, fill=255)
        im = im.crop((0, 0, adv, H))
        px = [min(15, (v + 8) >> 4) for v in im.getdata()]     # alpha 0..15
        if len(px) % 2: px.append(0)
        data = bytes((px[i] << 4) | px[i + 1] for i in range(0, len(px), 2))
        glyphs.append((ch, adv, data))
    return H, glyphs

lines = list(SET["head"])
total = 0
for name, fname, size, chars, track in SET["fonts"]:
    H, gl = build(name, fname, size, chars, track)
    bits = b"".join(g[2] for g in gl)
    offs, o = [], 0
    for g in gl: offs.append(o); o += len(g[2])
    total += len(bits)
    esc = chars.replace("\\", "\\\\").replace('"', '\\"')
    lines.append(f"/* {name}: {fname} {size}px, height {H} px, {len(gl)} chars, {len(bits)} bytes */")
    lines.append(f"static const uint8_t {name}_adv[{len(gl)}] = {{{', '.join(str(g[1]) for g in gl)}}};")
    lines.append(f"static const uint32_t {name}_off[{len(gl)}] = {{{', '.join(map(str, offs))}}};")
    hexs = ", ".join(f"0x{b:02X}" for b in bits)
    lines.append(f"static const uint8_t {name}_bits[{len(bits)}] = {{{hexs}}};")
    lines.append(f'static const op_font {name} = {{ {H}, "{esc}", {len(gl)}, {name}_adv, {name}_off, {name}_bits }};')
    lines.append("")
    print(f"{name}: {size}px {SET['face']} -> height {H}px, {len(gl)} glyphs, {len(bits)} bytes")
open(OUT, "w").write("\n".join(lines))
print(f"-> {os.path.normpath(OUT)} ({total} bytes of glyphs)")
