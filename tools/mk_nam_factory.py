# OpenPocket — writes firmware/apps/gamut/engine/px_nam_factory.h: the factory NAM models (A2-Lite weights, names, level trims).
#   mk_nam_factory.py CAPTURES [DI.wav]
# tools/nam_factory.txt lists the 12 models: "NAME|capture file|SHA-256|author|tone page". CAPTURES is a folder that holds
# the capture files (in any subfolder); each must have its SHA-256 and its author. Each model is the A2-Lite part of its
# capture, as the web editor imports one (docs/pxnam.js namEntry): scaled into the pedal's fixed-point range
# (nam_a2.fit_range: the output stays exactly the same), then its level trim, so that every model plays at the same
# loudness (tools/nam_level.py).
import hashlib, json, os, sys
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import nam_a2, nam_level

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIST = os.path.join(ROOT, "tools", "nam_factory.txt")


def cfloat(v):
    """a C float literal that round-trips the float32 (0 -> 0.0f, 1e-05 -> 1e-05f)"""
    s = "%.9g" % float(v)
    if not any(c in s for c in ".en"):
        s += ".0"
    return s + "f"


def rows():
    return [l.rstrip("\n").split("|") for l in open(LIST) if l.strip() and not l.startswith("#")]


def find(top, name):
    for d, _, files in os.walk(top):
        if name in files:
            return os.path.join(d, name)
    raise SystemExit("%s: not in %s" % (name, top))


def main():
    top = sys.argv[1]
    dip = sys.argv[2] if len(sys.argv) > 2 else None
    di = nam_level.di(dip)
    names, lv, ws, notes = [], [], [], []
    for name, fn, sha, author, page in rows():
        path = find(top, fn)
        raw = open(path, "rb").read()
        if hashlib.sha256(raw).hexdigest() != sha:
            raise SystemExit("%s: SHA-256 is not the listed one" % fn)
        j = json.loads(raw)
        if (j.get("metadata") or {}).get("modeled_by") != author:
            raise SystemExit("%s: modeled by %s, not %s" % (fn, (j.get("metadata") or {}).get("modeled_by"), author))
        m, c = nam_a2.pick(j, "lite")
        if c != 3 or len(name) > 8:
            raise SystemExit("%s: not A2-Lite, or a name longer than 8 characters" % fn)
        w, h = nam_a2.fit_range(m["weights"], di)
        ws.append(w)
        names.append(name)
        lv.append(nam_level.trim_db(nam_a2.unpack(w.astype(np.float64), 3), dip))
        notes.append((fn[:-4], author, page, h))
        print("%-8s level trim %+.2f dB%s" % (name, lv[-1], ", scaled by 1/%d" % 2 ** h if h else ""))
    if len(ws) != 12:
        raise SystemExit("want 12 models, got %d" % len(ws))
    out = ["/* SPDX-License-Identifier: GPL-3.0-only",
           " * OpenPocket — the factory NAM models (generated by tools/mk_nam_factory.py from tools/nam_factory.txt: do not edit).",
           " * The A2-Lite networks of NAM A2 captures published on TONE3000 (tone3000.com), used with their authors' written",
           " * permission (docs/NAM.md); the Neural Amp Modeler A2 architecture is Steven Atkinson's (MIT). Each capture, its",
           " * author on TONE3000 and its tone page:"]
    for n, (cap, author, page, h) in zip(names, notes):
        out.append(" *   %-8s %s, by %s%s" % (n, cap, author, " (scaled by 1/%d: the same output)" % 2 ** h if h else ""))
        out.append(" *            %s" % page)
    out += [" */", "#pragma once",
            "static const char *const PXN_FNAME[PX_NAM_NFACT] = {%s};" % ", ".join('"%s"' % n for n in names),
            "static const float PXN_FLVL[PX_NAM_NFACT] = {%s};" % ", ".join("%.2ff" % v for v in lv),
            "static const float PXN_FW[PX_NAM_NFACT][PXN_NW] = {"]
    for w in ws:
        vals = [cfloat(v) for v in w]
        lines = [", ".join(vals[i:i + 10]) for i in range(0, len(vals), 10)]
        out.append("  {" + ",\n   ".join(lines) + "},")
    out.append("};")
    open(os.path.join(ROOT, "firmware", "apps", "gamut", "engine", "px_nam_factory.h"), "w").write("\n".join(out) + "\n")
    print("firmware/apps/gamut/engine/px_nam_factory.h: %d models" % len(ws))


if __name__ == "__main__":
    main()
