// OpenPocket — writes firmware/apps/gamut/engine/px_ir_factory.h: slot IR1's factory cabinet IR, "BEST IR IN THE WORLD" by ML Sound Lab.
//   node tools/mk_ir_factory.mjs "ML Sound Lab's BEST IR IN THE WORLD.wav"
// The WAV is converted exactly as the web editor converts a user's (docs/pxir.js: onset, 44.1 kHz, 1024 samples, the
// 64-sample fade, int16 with its scale), so the factory IR plays as the same file loaded into a slot would. The WAV
// itself is not in the repository and not in the image; its SHA-256 is checked so the header is the one it gives.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseWav, prepareIr, packIr, IR_LEN } from "../docs/pxir.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SHA256 = "0cafcee04e2c9e6794b4d98c8fcf7168131b8eb78c460ed88d53f843983e4e2e";
const NAME = "ML BEST IR";
const CREDIT = "https://www.facebook.com/watch/?ref=embed_video&v=1053603041469100";

const file = process.argv[2];
if (!file) { console.error('usage: node tools/mk_ir_factory.mjs "ML Sound Lab\'s BEST IR IN THE WORLD.wav"'); process.exit(2); }
const buf = readFileSync(file);
const sha = createHash("sha256").update(buf).digest("hex");
if (sha !== SHA256) { console.error(`${file}: SHA-256 ${sha}, not the ML Sound Lab file's ${SHA256}`); process.exit(1); }

const w = parseWav(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const ir = prepareIr(w), packed = packIr(NAME, ir.h), v = new DataView(packed.buffer);
const scale = v.getFloat32(20, true), s = Array.from({ length: IR_LEN }, (_, i) => v.getInt16(64 + 2 * i, true));
const cf = (x) => { let t = String(Number(x.toPrecision(9))); if (!/[.e]/.test(t)) t += ".0"; return t + "f"; };   // a C float literal
const rows = [];
for (let i = 0; i < IR_LEN; i += 16) rows.push("  " + s.slice(i, i + 16).join(", ") + ",");
const out = [
  "/* SPDX-License-Identifier: GPL-3.0-only",
  " * OpenPocket — slot IR1's factory cabinet IR (generated by tools/mk_ir_factory.mjs: do not edit).",
  ' * "BEST IR IN THE WORLD", a free cabinet IR by ML Sound Lab, redistributed with the creator\'s permission as stated',
  ` * by the project's owner; the creator's video: ${CREDIT}`,
  ` * From its WAV (SHA-256 ${sha.slice(0, 16)}..., ${w.sampleRate / 1000} kHz, ${w.bits}-bit, ${w.x.length} frames), converted as the`,
  ` * editor converts a user's (docs/pxir.js): ${ir.note}.`,
  " * The engine plays it while slot IR1 holds no IR of the user's (firmware/apps/gamut/engine/px_dsp.c ir_get).",
  " * Sample k = PXI_FS[k] / 32767 * PXI_FSCALE.",
  " */",
  "#pragma once",
  `static const char PXI_FNAME[12] = "${NAME}";`,
  `static const float PXI_FSCALE = ${cf(scale)};`,
  "static const int16_t PXI_FS[PX_IR_LEN] = {",
  ...rows,
  "};",
];
writeFileSync(join(ROOT, "firmware", "apps", "gamut", "engine", "px_ir_factory.h"), out.join("\n") + "\n");
console.log(`firmware/apps/gamut/engine/px_ir_factory.h: ${NAME}, ${ir.note}, scale ${scale}`);
